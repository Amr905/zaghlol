// T-171 source guards (CLAUDE.md §2.2 and §2.6; NFR-PRIV-02; T-165 review
// F7). Run by app-ci's `flutter test` on every push:
//
// 1. No logging call anywhere in the app's production code: every Dart file
//    under lib/ and every Kotlin / Java / Swift file of every native folder
//    (capture, SMS, notification, spool, guard, ingest, share, OCR, backup /
//    iCloud, keys, attestation, seat keys, widget, wipe, clock, device, App
//    Intents, Share Extension, widget extension). This extends app-ci's
//    "no logging in key ... code" grep, which lists folders one by one, to
//    the whole tree, so a new folder is covered without a workflow edit.
// 2. F7: no plaintext key-value or shared/external storage API
//    (`UserDefaults`, `NSUbiquitousKeyValueStore`, `shared_preferences`,
//    `getLibraryDirectory`, Android external storage, SharedPreferences,
//    DataStore) in app code, except reviewed entries in [storageAllowed].

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

Directory appRoot() {
  var d = Directory.current.absolute;
  for (var i = 0; i < 6; i++) {
    if (File('${d.path}/pubspec.yaml').existsSync() &&
        Directory('${d.path}/lib').existsSync() &&
        Directory('${d.path}/android').existsSync()) {
      return d;
    }
    final app = Directory('${d.path}/app');
    if (app.existsSync()) return app;
    d = d.parent;
  }
  throw StateError('app root not found');
}

/// Production source roots, relative to app/.
const List<String> nativeRoots = [
  'android/app/src/main',
  'android/app/src/sms',
  'android/app/src/nosms',
  'android/app/src/devSms',
  'ios/Runner',
  'ios/Shared',
  'ios/ShareExtension',
  'ios/ZaghlolWidget',
];

/// Reviewed exceptions to the logging rule (relative path → reason).
const Map<String, String> loggingAllowed = {
  // Flutter-generated; logs only a plugin class name on a failed
  // registration, never app data. Not committed (regenerated by the tool).
  'android/app/src/main/java/io/flutter/plugins/GeneratedPluginRegistrant.java':
      'flutter tool output',
  // Dev-flavour SMS spike: logs a code and a duration only (T-008).
  'android/app/src/devSms/kotlin/app/zaghlol/spike/sms/SpikeLog.kt':
      'codes only, dev flavour',
};

final RegExp loggingCall = RegExp(
  r'\b(print|debugPrint|debugPrintStack|log|dump)\(|developer\.log|'
  r'\b(stdout|stderr)\b|\bLog\.[a-z]+\(|\bprintln\(|\bTimber\b|\bNSLog\b|'
  r'\bos_log\b|\bOSLog\b|\bLogger\(|\bprintStackTrace\(|\bSystem\.(out|err)\b|'
  r'\bfputs\(|FileHandle\.standardError|logStatements: *true',
);

/// F7 storage APIs that keep plaintext outside the encrypted stores, or
/// in places the OS backs up or shares.
final RegExp storageApi = RegExp(
  r'\bUserDefaults\b|\bNSUserDefaults\b|\bNSUbiquitousKeyValueStore\b|'
  r'\bshared_preferences\b|\bSharedPreferences\b|\bgetSharedPreferences\b|'
  r'\bPreferenceManager\b|androidx\.datastore|\bgetLibraryDirectory\b|'
  r'\bgetExternalStorageDirector(y|ies)\b|\bgetExternalCacheDir(s|ectories)?\b|'
  r'\bgetExternalFilesDirs?\b|\bgetDownloadsDirectory\b|'
  r'Environment\.getExternalStorage|\bMediaStore\b|MODE_WORLD_(READ|WRIT)ABLE',
);

/// Reviewed exceptions to F7 (relative path → tokens allowed there).
const Map<String, Set<String>> storageAllowed = {};

/// Drops `//` line comments, `/* */` block comments and Dart/Swift doc
/// comments, so prose may name a forbidden API. Strings stay (a call can
/// hide in an interpolation).
String code(String src) => src
    .replaceAll(RegExp(r'/\*.*?\*/', dotAll: true), '')
    .split('\n')
    .map((l) {
      final i = l.indexOf('//');
      if (i < 0) return l;
      // Keep `://` (URLs in strings).
      if (i > 0 && l[i - 1] == ':') return l;
      return l.substring(0, i);
    })
    .join('\n');

Iterable<File> sources(Directory app) sync* {
  for (final rel in ['lib', ...nativeRoots]) {
    final d = Directory('${app.path}/$rel');
    if (!d.existsSync()) continue;
    for (final f in d.listSync(recursive: true).whereType<File>()) {
      final p = f.path;
      if (p.endsWith('.dart') ||
          p.endsWith('.kt') ||
          p.endsWith('.java') ||
          p.endsWith('.swift') ||
          p.endsWith('.drift')) {
        yield f;
      }
    }
  }
}

void main() {
  final app = appRoot();
  String rel(File f) => f.path.substring(app.path.length + 1);

  test('the guards see every native folder (capture, share, widget, backup, '
      'keys, spool, guard, ingest, OCR, App Intents, extensions)', () {
    final dirs = {for (final f in sources(app)) File(f.path).parent.path};
    for (final want in [
      'kotlin/app/zaghlol/platform/capture',
      'kotlin/app/zaghlol/platform/spool',
      'kotlin/app/zaghlol/platform/guard',
      'kotlin/app/zaghlol/platform/ingest',
      'kotlin/app/zaghlol/platform/share',
      'kotlin/app/zaghlol/platform/widget',
      'kotlin/app/zaghlol/platform/keys',
      'kotlin/app/zaghlol/platform/ocr',
      'kotlin/app/zaghlol/platform/wipe',
      'src/sms/kotlin/app/zaghlol/platform/capture',
      'ios/Runner/Capture',
      'ios/Runner/Platform/ICloud',
      'ios/Runner/Platform/Share',
      'ios/Runner/Platform/OCR',
      'ios/Shared',
      'ios/ShareExtension',
      'ios/ZaghlolWidget',
      'lib/features/backup/application',
      'lib/features/capture/application',
      'lib/ingestion',
    ]) {
      expect(dirs.any((d) => d.endsWith(want)), isTrue, reason: want);
    }
  });

  test('no logging call in any production source (Dart, Kotlin, Java, '
      'Swift)', () {
    final hits = <String>[];
    for (final f in sources(app)) {
      if (loggingAllowed.containsKey(rel(f))) continue;
      final lines = code(f.readAsStringSync()).split('\n');
      for (var i = 0; i < lines.length; i++) {
        if (loggingCall.hasMatch(lines[i])) hits.add('${rel(f)}:${i + 1}');
      }
    }
    expect(hits, isEmpty);
  });

  test('F7: no plaintext key-value / external storage API in app code '
      '(reviewed exceptions only)', () {
    final hits = <String>[];
    for (final f in sources(app)) {
      final allowed = storageAllowed[rel(f)] ?? const <String>{};
      final lines = code(f.readAsStringSync()).split('\n');
      for (var i = 0; i < lines.length; i++) {
        for (final m in storageApi.allMatches(lines[i])) {
          if (!allowed.contains(m.group(0))) {
            hits.add('${rel(f)}:${i + 1} ${m.group(0)}');
          }
        }
      }
    }
    final pubspec = File('${app.path}/pubspec.yaml').readAsStringSync();
    if (RegExp(r'^\s+shared_preferences:', multiLine: true).hasMatch(pubspec)) {
      hits.add('pubspec.yaml shared_preferences');
    }
    expect(hits, isEmpty);
  });

  test('negative proof: the patterns catch planted calls and ignore prose', () {
    for (final bad in [
      'print(x);',
      'debugPrint(body);',
      'Log.d(TAG, body)',
      'NSLog("%@", body)',
      'os_log("x")',
      'Logger().info(x)',
      'System.out.println(x)',
      'e.printStackTrace()',
      'developer.log(x)',
    ]) {
      expect(loggingCall.hasMatch(code(bad)), isTrue, reason: bad);
    }
    expect(loggingCall.hasMatch(code('// never print(x) here')), isFalse);
    expect(loggingCall.hasMatch('final l = DiagLogger(store);'), isFalse);
    for (final bad in [
      'UserDefaults.standard.set(1, forKey: "k")',
      'NSUbiquitousKeyValueStore.default',
      "import 'package:shared_preferences/shared_preferences.dart';",
      'await getLibraryDirectory()',
      'context.getExternalFilesDir(null)',
      'Environment.getExternalStorageDirectory()',
      'context.getSharedPreferences("p", 0)',
    ]) {
      expect(storageApi.hasMatch(code(bad)), isTrue, reason: bad);
    }
    expect(
      storageApi.hasMatch(code('/// no UserDefaults (FR-SEC-03)')),
      isFalse,
    );
  });
}
