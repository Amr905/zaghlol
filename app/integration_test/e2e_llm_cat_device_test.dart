// T-363: device E2E of the automatic category (LLM-CATEGORISE) on the Android
// emulator, with a fake backend that runs inside the test (loopback HTTP).
// The real app (`main()`, real providers, real encrypted database, real SMS
// receiver); the backend is the only fake. Run twice by
// .github/scripts/e2e-llm-cat-device.sh, once per language (`E2E_LCAT_LANG`
// = ar | en).
//
// Flow: bank card-purchase SMS for three unknown shops (templates on the
// business allowlist), a wallet payment to a person-like name and a manual
// entry arrive -> the discovery card shows on Home -> the consent sheet names
// the provider -> "Not now" sends nothing -> Allow sends exactly the three
// shop names (no person, no manual entry, no amounts, dates or accounts) ->
// categories are applied only to "needs classification" rows, with the AI
// chip -> a tick makes a rule and the chip goes, a cross + pick replaces the
// guess and Undo restores it -> no `llmCatFeedback` leaves in any sync
// (`kSendLlmCatFeedback` is false) -> the Settings switch off clears the
// consent and empties the queue.
//
// The script sends the SMS when the test prints `E2ELCAT SEND <phase>`. The
// signing key and the proof key are generated by the script at run time and
// arrive as --dart-define values; none is committed. Synthetic data only;
// nothing is printed but counts, step names and the language.
//
// Run: see the script (it passes the defines).

