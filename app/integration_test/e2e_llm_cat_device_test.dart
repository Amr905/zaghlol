const String _lang = String.fromEnvironment(
  'E2E_LCAT_LANG',
  defaultValue: 'en',
);
const String _apiBase = String.fromEnvironment('ZAGHLOL_API_BASE');
const String _signScalar = String.fromEnvironment('E2E_FAKE_SIGN_D');
const String _proofKey = String.fromEnvironment('ZAGHLOL_LLM_DEV_KEY');

const String _providerId = 'e2e-test-provider';
const String _providerAr = 'مزود التجربة';
const String _providerEn = 'Test Provider';

// Synthetic shops that no catalog knows (so their rows need classification).
const String _shopA = 'QUIBLEXO';
const String _shopB = 'ZYMOTRON';
const String _shopC = 'BRAVEXO';
const String _shopQueued = 'DELTRAXA';
const String _person = 'MOHAMED HASSAN';

void main() {
  final e = E2e('E2ELCAT');
  final l = lookupAppLocalizations(Locale(_lang));

  testWidgets('automatic category: consent, send, apply, feedback, off', (
    t,
  ) async {
    HttpOverrides.global = null; // the real HttpClient, for the loopback fake
    await e.guarded(t, () async {
      e.say('LANG $_lang');
      if (_apiBase.isEmpty || _signScalar.isEmpty) {
        fail('the script must pass ZAGHLOL_API_BASE and E2E_FAKE_SIGN_D');
      }
      final backend = await FakeCatBackend.start(
        port: Uri.parse(_apiBase).port,
        kid: 's0000c',
        signingScalarB64Url: _signScalar,
        proofKeyB64: _proofKey,
        providerId: _providerId,
        providerNameAr: _providerAr,
        providerNameEn: _providerEn,
      );
      addTearDown(backend.stop);
      backend.answers.addAll({
        _shopA.toLowerCase(): const CatAnswer.llm('dining'),
        _shopB.toLowerCase(): const CatAnswer.cache('shopping', confidence: 90),
        _shopC.toLowerCase(): const CatAnswer.noAnswer(),
      });
      final providerName = _lang == 'ar' ? _providerAr : _providerEn;

      await e.seedReturningUser(
        language: _lang == 'ar' ? LanguagePref.ar : LanguagePref.en,
      );
      e.captureFlutterErrors();
      await app.main();
      e.say('MAIN_RETURNED');
      await e.waitFor(t, find.byType(ZBottomBar), what: 'the tab bar');
      await e.settle(t, 2000);

      final c = e.container();
      final db = await c.read(appDatabaseProvider.future);
      Future<List<Map<String, Object?>>> rows(String sql) async =>
          (await db.customSelect(sql).get()).map((r) => r.data).toList();
      Future<Map<String, Object?>?> txnOf(
        String norm, {
        String? source,
      }) async => (await rows(
        'SELECT id, category_id, category_source FROM transactions '
        "WHERE merchant_norm = '$norm' AND deleted_at IS NULL "
        "${source == null ? '' : "AND source = '$source' "}"
        'ORDER BY created_at LIMIT 1',
      )).firstOrNull;
      Future<void> go(String route) async {
        // The detail screen is pushed on the tab's own navigator (the device
        // run showed `go` leaving it on screen): pop it first.
        for (var i = 0; i < 3 && !e.found(find.byType(TxnRow)); i++) {
          await Navigator.of(t.element(find.byType(Scaffold).last)).maybePop();
          await e.settle(t, 800);
        }
        rootNavigatorKey.currentState?.popUntil((r) => r.isFirst);
        await e.settle(t, 300);
        GoRouter.of(rootNavigatorKey.currentContext!).go(route);
        await e.settle(t, 2000);
      }

      // ---- the app starts and syncs once with the fake backend.
      final synced = await _waitFor(
        t,
        () => backend.syncs.isNotEmpty,
        const Duration(seconds: 60),
      );
      e.check(synced, 'the app synced with the fake backend');
      e.check(
        backend.categorise.isEmpty,
        'nothing is sent to /v1/categorise before consent',
      );

      // ---- the data: a manual entry for a shop, a manual row for shop A
      // that the user already categorised, then the SMS.
      final accounts = await c.read(accountsRepositoryProvider.future);
      final txns = await c.read(transactionRepositoryProvider.future);
      final cash = await accounts.ensureDefaultCash(
        currency: Currency.of('EGP'),
        label: 'Cash',
      );
      Future<void> manual(String merchant, {String? categoryId}) async {
        final at = DateTime.now().subtract(const Duration(minutes: 30));
        await txns.add(
          NewTransaction(
            accountId: cash.id,
            direction: TxnDirection.expense,
            amount: Money(Currency.of('EGP'), 5000),
            occurredAt: at,
            occurredTzOffsetMin: at.timeZoneOffset.inMinutes,
            merchant: merchant,
            categoryId: categoryId,
          ),
        );
      }

      await manual('TEST SHOP A');
      await manual(_shopA, categoryId: 'sys:groceries');
      e.say('SEND p1');
      final arrived = await _waitFor(
        t,
        () async =>
            ((await rows(
                  "SELECT COUNT(*) AS n FROM transactions WHERE source = 'sms'",
                )).single['n']!
                as int) >=
            4,
        const Duration(seconds: 150),
      );
      e.check(arrived, 'the four SMS were saved');
      await e.settle(t, 3000);

      // ---- the discovery card appears on Home.
      final filler0 = await c.read(llmCatQueueFillerProvider.future);
      final card = find.byKey(const ValueKey('cat-discovery-card'));
      // Home is a long lazy list: the card is built only once scrolled to.
      Future<bool> findCardByScrolling() async {
        final list = find.byWidgetPredicate(
          (w) => w is Scrollable && w.axis == Axis.vertical,
        );
        for (var i = 0; i < 12 && !e.found(card); i++) {
          if (!e.found(list)) break;
          await t.drag(list.first, const Offset(0, -350), warnIfMissed: false);
          await e.settle(t, 400);
        }
        return e.found(card);
      }

      final shown = await _waitFor(
        t,
        findCardByScrolling,
        const Duration(seconds: 25),
      );
      // B98-m4: no provider refresh here. Home must follow rows the SMS
      // receiver writes while the app is open (Bug B); a missing card is a
      // failure (the DIAG block below says why).
      if (!shown) {
        final svc = await c.read(remoteConfigServiceProvider.future);
        final rc = c.read(remoteConfigProvider);
        e.say(
          'DIAG config svc=${svc.current.llmProvider.isNotEmpty} '
          'version=${svc.version} provider=${(rc.value != null) ? rc.value!.llmProvider.isNotEmpty : 'novalue'} '
          'names=${(rc.value != null) && rc.value!.providerName.en.isNotEmpty} '
          'termsProv=${c.read(llmProviderTermsProvider) != null}',
        );
        final flags = await c.read(flagsServiceProvider.future);
        e.say(
          'DIAG flagOn=${flags.isOn(FeatureFlag.llmCategorise)} '
          'terms=${c.read(llmCatTermsProvider) != null} '
          'eligible=${await filler0.countEligible(now: DateTime.now())} '
          'syncs=${backend.syncs.length}',
        );
        for (final r in await rows(
          'SELECT template_id, source, direction, counterparty_kind, '
          'category_source, is_internal, is_user_verified, '
          'merchant_norm IS NOT NULL AS has_norm, '
          'length(merchant_norm) AS len FROM transactions',
        )) {
          e.say('DIAG row $r');
        }
        c.invalidate(catCardVisibleProvider);
        final vis = await c.read(catCardVisibleProvider.future);
        final repo = await c.read(settingsRepositoryProvider.future);
        final sc = find
            .byWidgetPredicate(
              (w) => w is Scrollable && w.axis == Axis.vertical,
            )
            .evaluate()
            .map((el) => (el.widget as Scrollable).controller)
            .length;
        e.say(
          'DIAG visible=$vis shown=${await repo.get(CatCardSettings.shown)} '
          'never=${await repo.get(CatCardSettings.never)} '
          'consent=${await c.read(catConsentGrantedProvider.future)} '
          'vertical=$sc',
        );
        await e.shot(t, '$_lang-00-no-card');
        fail('the discovery card never appeared');
      }
      await e.shot(t, '$_lang-01-card');

      // ---- consent sheet: provider display name; "Not now" sends nothing.
      await e.scrollAndTap(
        t,
        find.byKey(const ValueKey('cat-card-allow')),
        'the card Allow button',
      );
      await e.waitFor(
        t,
        find.byKey(const ValueKey('cat-consent-sheet')),
        what: 'the consent sheet',
      );
      e.check(
        e.found(find.textContaining(providerName)),
        'the consent sheet shows the provider display name',
      );
      await e.shot(t, '$_lang-02-consent');
      await t.ensureVisible(find.byKey(const ValueKey('cat-consent-not-now')));
      await e.settle(t, 500);
      await t.tap(find.byKey(const ValueKey('cat-consent-not-now')));
      await e.settle(t, 3000);
      e.check(
        !e.found(find.byKey(const ValueKey('cat-consent-sheet'))),
        'the sheet closed on Not now',
      );
      e.check(
        backend.categorise.isEmpty,
        'zero /v1/categorise requests after Not now',
      );
      e.check(
        await LlmCatQueueDao(db).count() == 0,
        'the queue stays empty without consent',
      );

      // ---- Allow: exactly the three shop names are sent.
      await e.scrollAndTap(
        t,
        find.byKey(const ValueKey('cat-card-allow')),
        'the card Allow button (again)',
      );
      await e.waitFor(
        t,
        find.byKey(const ValueKey('cat-consent-allow')),
        what: 'the consent Allow button',
      );
      await t.ensureVisible(find.byKey(const ValueKey('cat-consent-allow')));
      await e.settle(t, 500);
      await t.tap(find.byKey(const ValueKey('cat-consent-allow')));
      final sent = await _waitFor(
        t,
        () => backend.categorise.isNotEmpty,
        const Duration(seconds: 60),
      );
      e.check(sent, 'a /v1/categorise request was made after Allow');
      await e.settle(t, 1500);
      e.check(
        backend.categorise.length == 1,
        'exactly one /v1/categorise request (got ${backend.categorise.length})',
      );
      if (backend.categorise.isNotEmpty) {
        final r = backend.categorise.first;
        final body = r.json ?? const <String, Object?>{};
        e.check(
          (body.keys.toList()..sort()).join(',') ==
              'attestation,consent,lang,merchants,requestId,v',
          'the body has only the contract members',
        );
        final merchants = ((body['merchants'] as List?) ?? const [])
            .cast<String>();
        e.check(
          merchants.toSet().length == 3 &&
              merchants.toSet().containsAll([
                _shopA.toLowerCase(),
                _shopB.toLowerCase(),
                _shopC.toLowerCase(),
              ]),
          'the request names exactly the three eligible shops '
          '(got ${merchants.length})',
        );
        e.check(
          merchants.every((m) => !RegExp(r'\d').hasMatch(m)),
          'no merchant carries a digit',
        );
        e.check(body['lang'] == _lang, 'the request language is $_lang');
        final text = (r.bodyText ?? '').toLowerCase();
        e.check(
          !text.contains('mohamed') &&
              !text.contains('hassan') &&
              !text.contains('test shop'),
          'the person payee and the manual entry are not in the body',
        );
        final consent = body['consent'];
        e.check(
          consent is Map &&
              consent['provider'] == _providerId &&
              consent.keys.length == 2,
          'the consent terms are the synced provider and version only',
        );
        e.check(
          r.attestationOk == true,
          'the dev proof verified against the body binding',
        );
      }

      // ---- categories applied only to rows that need classification.
      final applied = await _waitFor(
        t,
        () async =>
            ((await rows(
                  "SELECT COUNT(*) AS n FROM transactions WHERE category_source = 'ai'",
                )).single['n']!
                as int) >=
            2,
        const Duration(seconds: 30),
      );
      e.check(applied, 'two AI categories were applied');
      final a = await txnOf(_shopA.toLowerCase(), source: 'sms');
      final b = await txnOf(_shopB.toLowerCase(), source: 'sms');
      final cRow = await txnOf(_shopC.toLowerCase(), source: 'sms');
      e.check(
        a?['category_id'] == 'sys:dining' && a?['category_source'] == 'ai',
        'shop A got the ok/llm category as an AI guess',
      );
      e.check(
        b?['category_id'] == 'sys:shopping' && b?['category_source'] == 'ai',
        'shop B got the ok/cache category as an AI guess',
      );
      e.check(
        cRow?['category_id'] == null && cRow?['category_source'] == 'none',
        'the no-answer shop stays unclassified',
      );
      Future<Map<String, Object?>?> manualOf(String raw) async => (await rows(
        'SELECT category_id, category_source FROM transactions '
        "WHERE source = 'manual' AND merchant_raw = '$raw' LIMIT 1",
      )).firstOrNull;
      final userRow = await manualOf(_shopA);
      e.check(
        userRow?['category_id'] == 'sys:groceries' &&
            userRow?['category_source'] == 'user',
        'the user-categorised row of shop A is untouched',
      );
      final person = await txnOf(_person.toLowerCase());
      e.check(
        person?['category_source'] == 'none',
        'the person payment is untouched',
      );
      final manualRow = await manualOf('TEST SHOP A');
      e.check(
        manualRow?['category_source'] == 'none',
        'the manual entry is untouched',
      );
      e.check(!e.found(card), 'the discovery card is gone after consent');

      // ---- the list shows the AI chips.
      await go(AppRoutes.transactions);
      await e.waitFor(
        t,
        find.byKey(ValueKey(a!['id']! as String)),
        what: 'the shop A row',
      );
      e.check(
        find.byType(AiCategoryChip).evaluate().length == 2,
        'two AI chips in the list '
        '(got ${find.byType(AiCategoryChip).evaluate().length})',
      );
      await e.shot(t, '$_lang-03-list-chips');

      // ---- tick on shop A: a rule, the chip goes.
      await e.scrollAndTap(
        t,
        find.byKey(ValueKey(a['id']! as String)),
        'row A',
      );
      await e.scrollAndTap(
        t,
        find.byKey(const ValueKey('ai-right')),
        'the tick button',
      );
      await e.settle(t, 2500);
      await e.shot(t, '$_lang-04-tick');
      final rule = await rows(
        'SELECT category_id FROM merchant_rules '
        "WHERE match_kind = 'merchant_norm' "
        "AND match_value = '${_shopA.toLowerCase()}'",
      );
      e.check(
        rule.length == 1 && rule.single['category_id'] == 'sys:dining',
        'the tick made a rule for shop A',
      );
      final a2 = await txnOf(_shopA.toLowerCase(), source: 'sms');
      e.check(
        a2?['category_id'] == 'sys:dining' && a2?['category_source'] != 'ai',
        'shop A is confirmed (no longer an AI guess)',
      );
      e.check(
        !e.found(find.byType(AiCategoryChip)),
        'the chip is gone from shop A',
      );

      // ---- cross on shop B: pick, then Undo restores, then pick again.
      final groceries = (await rows(
        "SELECT name_ar, name_en FROM categories WHERE id = 'sys:groceries'",
      )).single;
      final groceriesName =
          (_lang == 'ar' ? groceries['name_ar'] : groceries['name_en'])!
              as String;
      Future<void> crossAndPick() async {
        await go(AppRoutes.transactions);
        e.say(
          'DIAG list rows=${find.byType(TxnRow).evaluate().length} '
          'rowB=${e.found(find.byKey(ValueKey(b!['id']! as String)))}',
        );
        await e.shot(t, '$_lang-05a-list');
        await e.scrollAndTap(
          t,
          find.byKey(ValueKey(b['id']! as String)),
          'row B',
        );
        await e.scrollAndTap(
          t,
          find.byKey(const ValueKey('ai-wrong')),
          'the cross button',
        );
        final pick = find.descendant(
          of: find.byType(ListTile),
          matching: find.text(groceriesName),
        );
        await e.waitFor(t, pick, what: 'the category picker');
        await e.shot(t, '$_lang-05-picker');
        await t.tap(pick.first);
        await e.settle(t, 1500);
      }

      await crossAndPick();
      var b2 = await txnOf(_shopB.toLowerCase(), source: 'sms');
      e.check(
        b2?['category_id'] == 'sys:groceries' && b2?['category_source'] != 'ai',
        'the picked category replaced the guess for shop B',
      );
      await e.waitFor(
        t,
        find.text(l.categorizationAiUndoAction),
        timeout: const Duration(seconds: 3),
        what: 'the Undo action',
      );
      await t.tap(find.text(l.categorizationAiUndoAction));
      await e.settle(t, 1500);
      await e.shot(t, '$_lang-06-undone');
      b2 = await txnOf(_shopB.toLowerCase(), source: 'sms');
      e.check(
        b2?['category_id'] == 'sys:shopping' && b2?['category_source'] == 'ai',
        'Undo within 5 s restored the AI guess for shop B',
      );
      await crossAndPick();
      b2 = await txnOf(_shopB.toLowerCase(), source: 'sms');
      e.check(
        b2?['category_id'] == 'sys:groceries' && b2?['category_source'] != 'ai',
        'shop B keeps the picked category',
      );

      // ---- sending feedback is off: no sync carries `llmCatFeedback`.
      final orchestrator = await c.read(syncOrchestratorProvider.future);
      await orchestrator.run(force: true);
      await e.settle(t, 1500);
      e.check(
        backend.syncs.length >= 2,
        'a second sync reached the fake backend '
        '(got ${backend.syncs.length})',
      );
      e.check(
        backend.syncs.every(
          (r) =>
              !(r.json ?? const <String, Object?>{}).containsKey(
                'llmCatFeedback',
              ) &&
              !(r.bodyText ?? '').contains('llmCatFeedback'),
        ),
        'no recorded sync request has an llmCatFeedback member',
      );

      // ---- a new shop is queued, then the Settings switch off.
      e.say('SEND p2');
      final more = await _waitFor(
        t,
        () async =>
            ((await rows(
                  "SELECT COUNT(*) AS n FROM transactions WHERE merchant_norm = '${_shopQueued.toLowerCase()}'",
                )).single['n']!
                as int) >=
            1,
        const Duration(seconds: 120),
      );
      e.check(more, 'the fifth SMS was saved');
      final filler = await c.read(llmCatQueueFillerProvider.future);
      await filler.fill(now: DateTime.now());
      e.check(
        await LlmCatQueueDao(db).count() == 1,
        'the new shop waits in the queue',
      );

      await go(AppRoutes.home);
      unawaited(openSettings(rootNavigatorKey.currentContext!));
      await e.scrollAndTap(
        t,
        find.text(l.settingsMainPrivacy),
        'the Privacy row',
      );
      final sw = find.byKey(const ValueKey('cat-llm-switch'));
      await e.scrollAndTap(t, sw, 'the switch');
      await e.settle(t, 2500);
      await e.shot(t, '$_lang-07-switch-off');
      final store = await c.read(llmConsentStoreProvider.future);
      final terms = c.read(llmCatTermsProvider);
      e.check(terms != null, 'the synced terms are known');
      if (terms != null) {
        e.check(
          await store.grantFor(
                LlmFeature.categorise,
                terms.provider,
                terms.v,
              ) ==
              null,
          'switching off cleared the consent',
        );
      }
      e.check(
        await LlmCatQueueDao(db).count() == 0,
        'switching off emptied the queue',
      );
      e.check(
        backend.categorise.length == 1,
        'nothing more was sent after switching off',
      );

      e.finish();
    });
  });
}

/// Polls [cond] (sync or async) while pumping frames.
Future<bool> _waitFor(
  WidgetTester t,
  FutureOr<bool> Function() cond,
  Duration timeout,
) async {
  final end = DateTime.now().add(timeout);
  while (DateTime.now().isBefore(end)) {
    await t.pump(const Duration(milliseconds: 300));
    if (await cond()) return true;
  }
  return cond();
}
