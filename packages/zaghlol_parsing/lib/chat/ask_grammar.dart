/// [_rawCues] with phrases folded and split into words.
final Map<AskIntent, List<({List<String> words, int weight})>> intentCues = {
  for (final e in _rawCues.entries)
    e.key: [
      for (final c in e.value)
        (
          words: foldKey(c.phrase)
              .split(' ')
              .where((w) => w.isNotEmpty)
              .toList(),
          weight: c.weight,
        ),
    ],
};

