// Generates lib/chat/llm/plan_schema.g.dart from the pinned ask-plan/1 schema
// (backend/contracts/ask-plan-v1.schema.json) and the shared vectors
// (templateBlanks, currencyExponents). T-331.
//
//   dart run tool/gen_plan_schema.dart           write the file
//   dart run tool/gen_plan_schema.dart --check   exit 1 if it is out of date
//
// Pure function [generatePlanSchemaDart] is also used by the regen test.
import 'dart:convert';
import 'dart:io';

String generatePlanSchemaDart(String schemaJson, String vectorsJson) {
  final schema = jsonDecode(schemaJson) as Map<String, Object?>;
  final vectors = jsonDecode(vectorsJson) as Map<String, Object?>;
  final defs = schema['\$defs']! as Map<String, Object?>;
  final props = schema['properties']! as Map<String, Object?>;

  final version = ((props['v']! as Map)['maximum']) as int;
  final plans = [
    for (final p in (props['plan']! as Map)['enum']! as List) p as String,
  ];
  final slugs = [
    for (final s in (defs['CategorySlug']! as Map)['enum']! as List)
      s as String,
  ];
  final blanksRaw = vectors['templateBlanks']! as Map<String, Object?>;
  final blanks = {
    for (final e in blanksRaw.entries)
      if (e.value is List)
        e.key: [for (final b in e.value! as List) b as String],
  };
  final exps = vectors['currencyExponents']! as Map<String, Object?>;
  final three = [for (final c in exps['3']! as List) c as String];
  final zero = [for (final c in exps['0']! as List) c as String];

  // The copy the phone interprets: no $schema, $id or $comment (the same
  // strip the provider adapters do).
  final stripped = Map<String, Object?>.of(schema)
    ..remove('\$schema')
    ..remove('\$id')
    ..remove('\$comment');
  final compact = jsonEncode(stripped);
  if (compact.contains("'''")) {
    throw StateError("schema contains ''' and cannot be embedded raw");
  }

  String list(List<String> xs) => '[${xs.map((x) => "'$x'").join(', ')}]';

  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_plan_schema.dart. Do not edit.')
    ..writeln('// Source: backend/contracts/ask-plan-v1.schema.json and')
    ..writeln(
      '// backend/tests/Zaghlol.Contract.Tests/vectors/ask-plan-v1.json.',
    )
    ..writeln('// dart format off')
    ..writeln('library;')
    ..writeln()
    ..writeln('/// `ask-plan/1`.')
    ..writeln('const int planVersion = $version;')
    ..writeln()
    ..writeln('/// Every plan name of the closed catalogue.')
    ..writeln('const List<String> planNames = ${list(plans)};')
    ..writeln()
    ..writeln('/// The system category codes a plan may name.')
    ..writeln('const List<String> planCategorySlugs = ${list(slugs)};')
    ..writeln()
    ..writeln(
      '/// Blanks a model template may use, per plan. A plan not listed here',
    )
    ..writeln('/// never uses a model template.')
    ..writeln('const Map<String, List<String>> planTemplateBlanks = {');
  for (final e in blanks.entries) {
    b.writeln("  '${e.key}': ${list(e.value)},");
  }
  b
    ..writeln('};')
    ..writeln()
    ..writeln(
      '/// ISO 4217 codes with 3 minor-unit digits (all others 2, see zero).',
    )
    ..writeln(
      'const Set<String> planThreeDecimalCurrencies = {${three.map((c) => "'$c'").join(', ')}};',
    )
    ..writeln()
    ..writeln('/// ISO 4217 codes with 0 minor-unit digits.')
    ..writeln(
      'const Set<String> planZeroDecimalCurrencies = {${zero.map((c) => "'$c'").join(', ')}};',
    )
    ..writeln()
    ..writeln(
      '/// The pinned schema, interpreted by the phone validator (step 1).',
    )
    ..writeln("const String planSchemaJson = r'''$compact''';");
  return b.toString();
}

void main(List<String> args) {
  final root = File.fromUri(Platform.script).parent.parent; // package root
  final repo = root.parent.parent;
  final schema = File('${repo.path}/backend/contracts/ask-plan-v1.schema.json')
      .readAsStringSync();
  final vectors = File(
    '${repo.path}/backend/tests/Zaghlol.Contract.Tests/vectors/ask-plan-v1.json',
  ).readAsStringSync();
  final out = File('${root.path}/lib/chat/llm/plan_schema.g.dart');
  final text = generatePlanSchemaDart(schema, vectors);
  if (args.contains('--check')) {
    if (!out.existsSync() || out.readAsStringSync() != text) {
      stderr.writeln(
        'plan_schema.g.dart is out of date: run tool/gen_plan_schema.dart',
      );
      exit(1);
    }
    return;
  }
  out.writeAsStringSync(text);
}
