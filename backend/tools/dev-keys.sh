#!/usr/bin/env sh
# Creates throwaway development KMS keys for `Kms:Provider = Local` (T-123) in backend/.dev-keys/ (git-ignored,
# docker-ignored) and the matching key-ring configuration in backend/.dev-keys/kms.env for docker compose.
#
#   backend/tools/dev-keys.sh          create the keys if they don't exist yet
#   backend/tools/dev-keys.sh --force  replace them (the app must re-embed the public JWKs)
#
# These keys are for local development only. The API refuses the Local provider outside the Development and
# Testing environments; staging and production keys live in the cloud KMS (T-140) and never leave it.
set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
dir="$here/../.dev-keys"

if [ -f "$dir/kms.env" ] && [ "${1:-}" != "--force" ]; then
  echo "dev keys already exist in backend/.dev-keys (use --force to replace them)"
  exit 0
fi

command -v openssl >/dev/null 2>&1 || { echo "openssl is required" >&2; exit 1; }

rm -rf "$dir"
mkdir -p "$dir"

b64url() { base64 | tr '+/' '-_' | tr -d '=\n'; }

# P-256 signing keys: s0000d signs response headers (Sync), e0000d signs JWS tokens (Entitlement).
for kid in s0000d e0000d; do
  openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out "$dir/$kid.pem" 2>/dev/null
done

# 32-byte keys: the three HMAC keys and the envelope key-encryption key.
for name in seat audit install-pepper envelope; do
  openssl rand -base64 32 > "$dir/$name.key"
done

# The API container runs as uid 1654 and reads the directory through a read-only bind mount, so the throwaway
# files are world-readable. Never do this with real keys.
chmod 755 "$dir"
chmod 644 "$dir"/*.pem "$dir"/*.key

jwk() {
  # The last 64 bytes of a P-256 SubjectPublicKeyInfo are X || Y.
  x=$(openssl pkey -in "$dir/$1.pem" -pubout -outform DER 2>/dev/null | tail -c 64 | head -c 32 | b64url)
  y=$(openssl pkey -in "$dir/$1.pem" -pubout -outform DER 2>/dev/null | tail -c 32 | b64url)
  echo "Signing__Keys__$2__Kid=$1"
  echo "Signing__Keys__$2__Purpose=$3"
  echo "Signing__Keys__$2__Status=Active"
  echo "Signing__Keys__$2__KeyRef=local:$1"
  echo "Signing__Keys__$2__PublicJwk__Kty=EC"
  echo "Signing__Keys__$2__PublicJwk__Crv=P-256"
  echo "Signing__Keys__$2__PublicJwk__X=$x"
  echo "Signing__Keys__$2__PublicJwk__Y=$y"
}

{
  echo "# Generated by backend/tools/dev-keys.sh: development key ring for Kms:Provider=Local."
  echo "Kms__Provider=Local"
  echo "Kms__Local__KeyDirectory=/run/zaghlol-dev-keys"
  echo "Kms__HmacKeys__Seat=local:seat"
  echo "Kms__HmacKeys__Audit=local:audit"
  echo "Kms__HmacKeys__InstallHashPepper=local:install-pepper"
  echo "Kms__Envelope__KeyRef=local:envelope"
  jwk s0000d 0 Sync
  jwk e0000d 1 Entitlement
} > "$dir/kms.env"
chmod 644 "$dir/kms.env"

echo "dev keys written to backend/.dev-keys (public JWKs in kms.env)"
