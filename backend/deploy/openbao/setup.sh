#!/bin/sh
# OpenBao set-up for the Zaghlol Transit KMS (T-201; design note docs/03-technical/design-notes/T-201.md §4, §7;
# operator steps: docs/03-technical/deployment.md §3 "OpenBao Transit KMS").
#
#   setup.sh policy api|worker|keytool   print one policy (HCL) from the key lists below; needs no server
#   setup.sh apply <out-dir>             create the mount, keys, policies, AppRoles, credentials and the key-tool token
#
# Runs in a one-off container of the OpenBao image on the kms network (the bao CLI; deployment.md §3 step 3), with
# BAO_ADDR=https://openbao:8200, BAO_CACERT and an admin BAO_TOKEN in the environment, and a writable <out-dir> mount.
# Re-runnable: keys are never re-created or changed (Transit's create is a no-op on an existing key, and the type is
# checked), roles and policies are rewritten, an existing secret-id file is kept. Nothing secret is printed: role-id,
# secret-id and the key-tool token go to files under <out-dir> (umask 077).
#
# Key lists (space-separated names; a-z, 0-9, '-'):
#   ZAGHLOL_MOUNT                 Transit mount (default transit)
#   ZAGHLOL_KIDS                  ecdsa-p256 signing keys, one per kid, created here (e.g. "s2027a e2027a")
#   ZAGHLOL_HMAC_KEYS             hmac keys, imported by the key tool from the File keys (default "seat audit install-pepper")
#   ZAGHLOL_ENVELOPE_KEYS         aes256-gcm96 envelope keys, created here (e.g. "envelope-2027")
#   ZAGHLOL_LEGACY_ENVELOPE_KEYS  File envelope keys imported as file-<name>, decrypt only (e.g. "envelope"; may be empty)
#   ZAGHLOL_BOUND_CIDRS           comma-separated CIDRs the AppRole secret-ids and tokens are bound to (the stack network);
#                                 required by apply (review S2): unbound credentials would work from anywhere
#   ZAGHLOL_AUDIT_FILE            only if no audit device is declared in openbao.hcl and API creation is allowed (CI)
set -eu

MOUNT="${ZAGHLOL_MOUNT:-transit}"
KIDS="${ZAGHLOL_KIDS:-}"
HMAC_KEYS="${ZAGHLOL_HMAC_KEYS:-seat audit install-pepper}"
ENVELOPE_KEYS="${ZAGHLOL_ENVELOPE_KEYS:-}"
LEGACY_ENVELOPE_KEYS="${ZAGHLOL_LEGACY_ENVELOPE_KEYS:-}"
BOUND_CIDRS="${ZAGHLOL_BOUND_CIDRS:-}"

die() {
  echo "setup.sh: $*" >&2
  exit 1
}

check_name() {
  case "$1" in
    "" | *[!a-z0-9-]* | -*) die "invalid name '$1' (a-z, 0-9, '-'; not starting with '-')" ;;
  esac
  [ "${#1}" -le 63 ] || die "name too long: $1"
}

for n in $MOUNT $KIDS $HMAC_KEYS $ENVELOPE_KEYS; do check_name "$n"; done
for n in $LEGACY_ENVELOPE_KEYS; do check_name "file-$n"; done
for k in $KIDS; do
  case "$k" in
    [se][0-9][0-9][0-9][0-9][a-z]) ;;
    *) die "kid '$k' must match ^[se][0-9]{4}[a-z]$" ;;
  esac
  case "$k" in ?0000?) die "kid '$k': year 0000 is for development and tests only" ;; esac
done

# One path stanza.
p() {
  printf 'path "%s" {\n  capabilities = [%s]\n}\n\n' "$1" "$2"
}

# What no Zaghlol process may ever do on the mount or the server (explicit, on top of deny-by-default).
denies() {
  p "$MOUNT/export/*" '"deny"'
  p "$MOUNT/backup/*" '"deny"'
  p "$MOUNT/restore*" '"deny"'
  p "$MOUNT/keys/+/config" '"deny"'
  p "$MOUNT/keys/+/rotate" '"deny"'
  p "$MOUNT/keys/+/trim" '"deny"'
  p "$MOUNT/datakey/wrapped/*" '"deny"'
  p "sys/*" '"deny"'
}

envelope_paths() {
  for e in $ENVELOPE_KEYS; do
    p "$MOUNT/keys/$e" '"read"'
    p "$MOUNT/datakey/plaintext/$e" '"update"'
    p "$MOUNT/decrypt/$e" '"update"'
    p "$MOUNT/hmac/$e/sha2-256" '"update"'
  done
  for l in $LEGACY_ENVELOPE_KEYS; do
    p "$MOUNT/keys/file-$l" '"read"'
    p "$MOUNT/decrypt/file-$l" '"update"'
    p "$MOUNT/hmac/file-$l/sha2-256" '"update"'
  done
}

policy() {
  case "$1" in api | worker | keytool) ;; *) die "policy: api, worker or keytool" ;; esac
  echo "# zaghlol-$1 (generated by backend/deploy/openbao/setup.sh; T-201 design note §4). Do not edit by hand."
  echo
  case "$1" in
    api)
      for k in $KIDS; do
        p "$MOUNT/keys/$k" '"read"'
        p "$MOUNT/sign/$k/sha2-256" '"update"'
      done
      for h in $HMAC_KEYS; do
        p "$MOUNT/keys/$h" '"read"'
        p "$MOUNT/hmac/$h/sha2-256" '"update"'
      done
      envelope_paths
      p "$MOUNT/keys/+/import*" '"deny"'
      p "$MOUNT/wrapping_key" '"deny"'
      denies
      ;;
    worker)
      envelope_paths
      p "$MOUNT/keys/+/import*" '"deny"'
      p "$MOUNT/wrapping_key" '"deny"'
      denies
      ;;
    keytool)
      p "$MOUNT/wrapping_key" '"read"'
      for h in $HMAC_KEYS; do
        p "$MOUNT/keys/$h" '"read"'
        p "$MOUNT/keys/$h/import" '"create", "update"'
        p "$MOUNT/hmac/$h/sha2-256" '"update"'
      done
      for l in $LEGACY_ENVELOPE_KEYS; do
        p "$MOUNT/keys/file-$l" '"read"'
        p "$MOUNT/keys/file-$l/import" '"create", "update"'
        p "$MOUNT/decrypt/file-$l" '"update"'
        p "$MOUNT/hmac/file-$l/sha2-256" '"update"'
      done
      for k in $KIDS; do
        p "$MOUNT/keys/$k" '"read"'
      done
      for e in $ENVELOPE_KEYS; do
        p "$MOUNT/keys/$e" '"read"'
        p "$MOUNT/hmac/$e/sha2-256" '"update"'
      done
      denies
      ;;
    *) die "policy: api, worker or keytool" ;;
  esac
}

# Creates a key if it is missing (Transit's create never changes an existing key) and checks its type and flags.
ensure_key() {
  name="$1"
  type="$2"
  bao write -f "$MOUNT/keys/$name" type="$type" exportable=false allow_plaintext_backup=false >/dev/null
  have=$(bao read -field=type "$MOUNT/keys/$name")
  [ "$have" = "$type" ] || die "key $name exists with type $have, expected $type; fix it by hand (never re-created here)"
  [ "$(bao read -field=exportable "$MOUNT/keys/$name")" = "false" ] || die "key $name is exportable"
  [ "$(bao read -field=allow_plaintext_backup "$MOUNT/keys/$name")" = "false" ] || die "key $name allows plaintext backup"
  [ "$(bao read -field=deletion_allowed "$MOUNT/keys/$name")" = "false" ] || die "key $name allows deletion"
  echo "key: $name ($type)"
}

role() {
  name="$1"
  set -- token_policies="$name" token_no_default_policy=true token_type=service token_ttl=1h token_max_ttl=4h \
    secret_id_num_uses=0 secret_id_ttl=0 secret_id_bound_cidrs="$BOUND_CIDRS" token_bound_cidrs="$BOUND_CIDRS"
  bao write "auth/approle/role/$name" "$@" >/dev/null
  echo "approle: $name"
}

credentials() {
  name="$1"
  dir="$2"
  mkdir -p "$dir"
  bao read -field=role_id "auth/approle/role/$name/role-id" >"$dir/role-id"
  if [ -s "$dir/secret-id" ]; then
    echo "credentials: $dir/secret-id kept (destroy it and re-run to issue a new one)"
  else
    bao write -f -field=secret_id "auth/approle/role/$name/secret-id" >"$dir/secret-id"
    echo "credentials: $dir/role-id, $dir/secret-id written (not printed)"
  fi
  chmod 0400 "$dir/role-id" "$dir/secret-id"
}

apply() {
  out="$1"
  umask 077
  [ -n "$BOUND_CIDRS" ] || die "ZAGHLOL_BOUND_CIDRS is required (the kms network, e.g. 172.30.53.0/24): secret-ids and tokens must be bound to it"
  mkdir -p "$out"

  bao status >/dev/null 2>&1 || die "OpenBao is sealed, uninitialised or unreachable (bao status)"

  # Audit: declared in openbao.hcl in production. API creation works only where unsafe_allow_api_audit_creation is set.
  if ! bao audit list -format=json 2>/dev/null | grep -q '"type"'; then
    if [ -n "${ZAGHLOL_AUDIT_FILE:-}" ]; then
      bao audit enable -path=zaghlol-file file file_path="$ZAGHLOL_AUDIT_FILE" >/dev/null
    fi
    bao audit list -format=json 2>/dev/null | grep -q '"type"' || die "no audit device: declare audit \"file\" in openbao.hcl"
  fi
  echo "audit: enabled"

  if ! bao secrets list -format=json | grep -q "\"$MOUNT/\""; then
    bao secrets enable -path="$MOUNT" transit >/dev/null
  fi
  echo "mount: $MOUNT"

  for k in $KIDS; do ensure_key "$k" ecdsa-p256; done
  for e in $ENVELOPE_KEYS; do ensure_key "$e" aes256-gcm96; done

  for name in api worker keytool; do
    policy "$name" | bao policy write "zaghlol-$name" - >/dev/null
    echo "policy: zaghlol-$name"
  done

  if ! bao auth list -format=json | grep -q '"approle/"'; then
    bao auth enable approle >/dev/null
  fi
  role zaghlol-api
  role zaghlol-worker
  credentials zaghlol-api "$out/api"
  credentials zaghlol-worker "$out/worker"

  # The key tool's token: 15 minutes, 40 uses, the keytool policy only. Revoke it after the import (bao token revoke).
  bao token create -policy=zaghlol-keytool -no-default-policy -ttl=15m -use-limit=40 -field=token >"$out/keytool-token"
  chmod 0400 "$out/keytool-token"
  echo "keytool token: $out/keytool-token (15 min; not printed)"
  echo "next: run the key tool (--openbao-keys), copy ca.pem into each credential folder, chown to the app uid (deployment.md §3)"
}

case "${1:-}" in
  policy) policy "${2:-}" ;;
  apply) [ -n "${2:-}" ] || die "apply <out-dir>"; apply "$2" ;;
  *) die "usage: setup.sh policy api|worker|keytool | setup.sh apply <out-dir>" ;;
esac
